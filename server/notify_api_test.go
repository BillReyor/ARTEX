// This document covers the end-to-end behavior of the push function: vulnerability logging → event → dispatch → real HTTP.
//
// A security note: these use cases do not call the global Notifier.step()**, only the ones created by themselves.
// The channel calls stepRealtime/stepDigest. The reason is that step() will traverse all enabled channels in the library——
// Run the test on a development library that has been equipped with a real DingTalk/Qiwei robot. The global step will
// The resulting loopholes are really pushed to those groups. Channel-by-channel calls strictly limit the impact to the fake receiving end created by the test.
//
// Cleanup: When the use case ends, delete the events (cascade deletion and delivery) and channels generated by this use case, so as not to leave a backlog for the real channels.
//
// Assertion caliber: stepRealtime/stepDigest does not return a value and records internal logs, so what is asserted here is
// **observable external behavior** (what the fake receiver receives, what state the delivery line falls into), not the function's
// Return value - This is closer to the real call path than stubbing the return value.

// notifyFixture is a public device for use cases in this document.
type notifyFixture struct {
	s       *Server
	pg      *db.DB
	request func(method, path, body string) *httptest.ResponseRecorder
	n       *Notifier
	// Self-built task/exploration: The use case records the vulnerability here and isolates it from the data of other use cases.
	taskID int64
	expID  int64
	// Events generated after cleanupMark are deleted during cleanup.
	cleanupMark int64
}

func newNotifyFixture(t *testing.T) *notifyFixture {
	t.Helper()
	// All fake receivers in this file run on 127.0.0.1, and delivery rejects loopback addresses by default.
	// (Prevent SSRF from hitting co-host services and cloud metadata). Test explicitly turning on this switch;
	// The behavior of guarding "default reject" is overridden by ssrf_test.go of the notify package.
	t.Setenv(notify.AllowLocalTargetsEnv, "1")
	s, _, request := trafficEvidenceServer(t)
	pg := s.m.pg

	// Build a task by yourself: The task created by the shared device trafficEvidenceServer cannot get the exploration id.
	// And documenting vulnerabilities must provide it.
	task, err := s.m.CreateTask("通知推送测试", "推送行为验证", nil, 0, 0)
	if err != nil {
		t.Fatal(err)
	}
	taskID, err := strconv.ParseInt(task.ID, 10, 64)
	if err != nil {
		t.Fatal(err)
	}
	t.Cleanup(func() { pg.Exec(`DELETE FROM tasks WHERE id=$1`, taskID) })

	var mark int64
	if err := pg.QueryRow(`SELECT COALESCE(max(id),0) FROM notification_events`).Scan(&mark); err != nil {
		t.Fatal(err)
	}
	// Let the device close its own loop: Mark events that existed before the fixture was created as dispatched at once.
	//
	// Why it must be done: FanOutPendingEvents is **global** and will store all undispatched events in the library
	// Expand to all matching channels. The shared device trafficEvidenceServer itself will record a vulnerability
	// (exactly the initial finding it returns), other use cases may have remnants as well. If there is no isolation,
	// These spurious events will be dispatched to the channel of this use case, allowing assertions such as "There should be N deliveries"
	// Sometimes it's right, sometimes it's wrong - and the wrong way depends on the order of use case execution, which is more difficult to detect than direct failure.
	if _, err := pg.Exec(`UPDATE notification_events SET fanned_out = true WHERE id <= $1 AND NOT fanned_out`, mark); err != nil {
		t.Fatal(err)
	}

	f := &notifyFixture{s: s, pg: pg, request: request, n: newNotifier(s), taskID: taskID, expID: task.ExpID, cleanupMark: mark}
	t.Cleanup(func() {
		if _, err := pg.Exec(`DELETE FROM notification_events WHERE id > $1`, f.cleanupMark); err != nil {
			t.Logf("Cleanup notification event failed: %v", err)
		}
	})
	// The master switch must be on (other use cases may turn it off).
	if err := pg.SetBool(settingNotifyEnabled, true); err != nil {
		t.Fatal(err)
	}
	return f
}

// Record takes the real evidence writing path and finds a loophole, returning the finding id.
// This path will register the push event in the same transaction - which is the hanging point of this function.
func (f *notifyFixture) record(t *testing.T, vulnclass, severity string) int64 {
	t.Helper()
	out, err := f.s.evidenceStore().Record(context.Background(), db.RecordFindingInput{
		TaskID:        f.taskID,
		ExplorationID: f.expID,
		Worker:        "test",
		VulnClass:     vulnclass,
		Name:          vulnclass,
		Severity:      severity,
		Summary:       vulnclass + " 的摘要",
		Evidence:      "poc",
	}, nil)
	if err != nil {
		t.Fatalf("Failed to log vulnerability: %v", err)
	}
	return out.FindingID
}

