// TestNotifyDigestSegmentsAndDefersRemainder is the end-to-end proof of "silent loss" repair.
//
// The summary message is subject to the upper limit of the channel length (4096 bytes for Qiwei). When a batch cannot be loaded, it must be split into entire messages:
// Those tags loaded into this item have been delivered, and the rest are returned to the queue to wait for the next item. The previous implementation was to mark the entire batch
// Success - the truncated ones are neither in the message nor in the failure list, and the delivery history still shows success.
// The loophole is gone.
//
// Assert four things: ① Only the number of items actually loaded is marked ② The rest are still pending ③ Postponed items
// **The number of retries is not consumed** ④ Another round can be used to send out the rest (it will not get stuck).
func TestNotifyDigestSegmentsAndDefersRemainder(t *testing.T) {
	f := newNotifyFixture(t)
	hook := newFakeWebhook(t)
	// Using Enterprise WeChat: The upper limit of markdown is 4096 bytes, which is the tightest among the six channels.
	chID := f.createChannel(t, map[string]any{
		"name":   "分段汇总",
		"kind":   notify.KindWeCom,
		"mode":   db.NotifyModeDigest,
		"config": map[string]any{"webhook": hook.URL},
	})
	const total = 60
	// Make the title longer, ensuring that 60 entries are far more than 4096 bytes and must be segmented.
	longName := strings.Repeat("超长漏洞名称", 6)
	for i := 0; i < total; i++ {
		f.record(t, longName+strconv.Itoa(i+1), "high")
	}
	ctx := context.Background()
	if _, _, err := f.pg.FanOutPendingEvents(ctx, 500); err != nil {
		t.Fatal(err)
	}
	f.agePendingBatch(t, chID)
	ch := f.channel(t, chID)

	f.n.stepDigest(ctx, ch, 50, "")
	if hook.count() != 1 {
		t.Fatalf("Should only send one message, get %d", hook.count())
	}

	var sent, pending int
	if err := f.pg.QueryRow(`SELECT
    count(*) FILTER (WHERE state=$2),
    count(*) FILTER (WHERE state=$3)
  FROM notification_deliveries WHERE channel_id=$1`, chID, db.NotifyStateSent, db.NotifyStatePending).
		Scan(&sent, &pending); err != nil {
		t.Fatal(err)
	}
	if sent == 0 {
		t.Fatal("Items should be marked as delivered")
	}
	if pending == 0 {
		t.Fatalf("It is impossible for a batch of %d items to fit into all 4096 bytes, and there should be some left to be sent; sent=%d", total, sent)
	}
	if sent+pending != total {
		t.Fatalf("The number of entries does not match: sent=%d pending=%d total=%d (neither delivered nor pending = lost)", sent, pending, total)
	}
	// The text of the message must truthfully state how many messages are not included in this article.
	if text := markdownText(t, hook.last(t)); !strings.Contains(text, "remaining") {
		t.Fatalf("The message should state that there are items not included in this article:\n%.400s", text)
	}

	// Delayed entries must not consume the retry budget: attempts are already optimistic +1 when claimed, and are reduced back when deferred.
	var maxAttempts int
	if err := f.pg.QueryRow(`SELECT COALESCE(max(attempts),0) FROM notification_deliveries
WHERE channel_id=$1 AND state=$2`, chID, db.NotifyStatePending).Scan(&maxAttempts); err != nil {
		t.Fatal(err)
	}
	if maxAttempts > 0 {
		t.Fatalf("Postponed entries should not consume the number of retries (otherwise they will be deemed failed after a few entries), resulting in attempts=%d", maxAttempts)
	}

	// Repeat until convergence. What is asserted is that **all of them were finally delivered** and it did take multiple rounds along the way——
	// This is stronger than "the second round is distributed": it proves that the segments will not be stuck and the remaining entries will not be lost.
	rounds := 0
	for {
		var undelivered int
		if err := f.pg.QueryRow(`SELECT count(*) FROM notification_deliveries
WHERE channel_id=$1 AND state <> $2 AND state <> $3`, chID, db.NotifyStateSent, db.NotifyStateFailed).
			Scan(&undelivered); err != nil {
			t.Fatal(err)
		}
		if undelivered == 0 {
			break
		}
		rounds++
		if rounds > total+5 {
			t.Fatalf("Segmented delivery does not converge: after running %d rounds, there are still %d items pending.", rounds, undelivered)
		}
		before := hook.count()
		f.n.stepDigest(ctx, ch, 50, "")
		if hook.count() == before {
			t.Fatalf("There is no progress in round %d, and the remaining %d items will be permanently stuck.", rounds, undelivered)
		}
	}
	if rounds < 2 {
		t.Fatalf("A 4096-byte message cannot fit in the %d long header vulnerability. It should be sent in multiple rounds. In fact, only the %d round was used.", total, rounds)
	}
	// Each round after the first round should be **purely issued**, with no entries rejected by the channel.
	var failed int
	if err := f.pg.QueryRow(`SELECT count(*) FROM notification_deliveries WHERE channel_id=$1 AND state=$2`,
		chID, db.NotifyStateFailed).Scan(&failed); err != nil {
		t.Fatal(err)
	}
	if failed != 0 {
		t.Fatalf("If the fake receiver always returns success, there should be no failed entries, and you get %d", failed)
	}
}

// TestNotifyBackoffTableMatchesAttemptBudget is an anti-drift assertion.
//
// The retry budget (db.MaxNotifyAttempts) and the backoff sequence list (notifyBackoff) are separated into two packages:
// The former is the strategy of the state machine, and the latter is the execution rhythm of the engine. If only one of them is changed - for example, the budget is raised to 5
// I forgot to add the backoff gear once - the code will not report an error, but will only let the 4th and 5th retries use the last gear interval.
// The performance is "the retry rhythm is inexplicably slowed down", and it is difficult to think of this when troubleshooting.
// Assert that the two lengths are the same so that this drift is exposed in CI.
func TestNotifyBackoffTableMatchesAttemptBudget(t *testing.T) {
	if len(notifyBackoff) != db.MaxNotifyAttempts {
		t.Fatalf("The number of back-off gears (%d) is inconsistent with the maximum number of attempts (%d) - changing one must change the other at the same time",
			len(notifyBackoff), db.MaxNotifyAttempts)
	}
	// The backoff interval must be monotonous, otherwise the retries will become more and more urgent, which will intensify the current limit.
	for i := 1; i < len(notifyBackoff); i++ {
		if notifyBackoff[i] < notifyBackoff[i-1] {
			t.Fatalf("The backoff interval must be monotonic: %d %v < %d %v",
				i, notifyBackoff[i], i-1, notifyBackoff[i-1])
		}
	}
}

// TestNotifyRateLimitDoesNotConsumeRetryBudget locks the order of "get the token first and then receive it".
// If it is reversed (first received and then abandoned), the delivery blocked by the current limit has already been counted as an attempt.
// The budget will be exhausted by pure waiting, and finally fall into failed.
func TestNotifyRateLimitDoesNotConsumeRetryBudget(t *testing.T) {
	// Only the token bucket itself is tested, no Server is required (and one should not be created for it).
	n := &Notifier{buckets: map[int64]*notifyBucket{}}
	now := time.Now()
	// 1 per minute: Maximum 1 when the bucket is full.
	if got := n.takeTokens(1, 1, notifyMaxSendsPerChannelPerTick, now); got != 1 {
		t.Fatalf("When the bucket is full, 1 token should be taken per minute, and %d is obtained.", got)
	}
	if got := n.takeTokens(1, 1, notifyMaxSendsPerChannelPerTick, now.Add(time.Millisecond)); got != 0 {
		t.Fatalf("It should return 0 immediately after the token is exhausted, resulting in %d", got)
	}
	if got := n.takeTokens(1, 1, notifyMaxSendsPerChannelPerTick, now.Add(30*time.Second)); got != 0 {
		t.Fatalf("Halfway should not fill up a token, get %d", got)
	}
	if got := n.takeTokens(1, 1, notifyMaxSendsPerChannelPerTick, now.Add(time.Minute)); got != 1 {
		t.Fatalf("After a full period, 1 token should be replenished and %d should be obtained.", got)
	}
	// Unlimited channels use limited upper limits to avoid being held back by unlimited backlogs in a single cycle.
	if got := n.takeTokens(2, 0, notifyUnlimitedBurstPerTick+10, now); got != notifyUnlimitedBurstPerTick {
		t.Fatalf("If the current is not limited, the upper limit of each round should be returned to %d, and %d is obtained.", notifyUnlimitedBurstPerTick, got)
	}
	// Token buckets between channels are independent of each other.
	if got := n.takeTokens(1, 1, notifyMaxSendsPerChannelPerTick, now.Add(time.Millisecond)); got != 0 {
		t.Fatalf("Channel 1's bucket should still be empty, getting %d", got)
	}
}

// TestNotifyTakeTokensKeepsUnusedTokens locks the semantics of "only take the wanted ones".
//
// In previous implementations, the bucket was completely emptied before being truncated by the caller. Therefore, the channel with rate=100/min filled the bucket.
// Only 5 tokens are used in one round, and the remaining 95 tokens are discarded directly; if the channel has no pending delivery in this round, it will also be deducted.
// The result is that the comment's claim that "rate_per_min items can be flushed at once during the backlog" cannot be achieved under any circumstances.
func TestNotifyTakeTokensKeepsUnusedTokens(t *testing.T) {
	n := &Notifier{buckets: map[int64]*notifyBucket{}}
	now := time.Now()
	// The bucket is initially full (100), and there are only 5 in this round.
	if got := n.takeTokens(1, 100, 5, now); got != 5 {
		t.Fatalf("When want=5, exactly 5 tokens should be taken to get %d", got)
	}
	// Key assertion: The remaining 95 must still be in the bucket and not be pumped out and discarded.
	// Not advancing time ensures that what you get can only come from the stock rather than replenishing it.
	if got := n.takeTokens(1, 100, 95, now); got != 95 {
		t.Fatalf("Remaining tokens should still be available (expect 95), get %d - the bucket is emptied for the entire round", got)
	}
	if got := n.takeTokens(1, 100, 1, now); got != 0 {
		t.Fatalf("The bucket has been exhausted, so 0 should be returned and %d is obtained.", got)
	}
	// want<=0 should not deduct any tokens (no charge for empty rounds).
	n2 := &Notifier{buckets: map[int64]*notifyBucket{}}
	if got := n2.takeTokens(1, 20, 0, now); got != 0 {
		t.Fatalf("want=0 should return 0, getting %d", got)
	}
	if got := n2.takeTokens(1, 20, 20, now); got != 20 {
		t.Fatalf("The token should not be consumed when want=0, and it should still be possible to get 20, and get %d", got)
	}
}

// TestDigestTickPlanDecouplesBatchSizeFromSendBudget Tacks two dimensions of summary mode.
//
// Once the size of the summary batch is linked to the request budget of each round, the channel with rate_per_min=20 can only
// 1 token is added in 3 seconds tick, so each summary message only contains 1 vulnerability - functionally equivalent to none
// Summary, and the header of the message also says "1 new vulnerability has been added in the past 30 minutes." This degradation will not report an error,
// The existing end-to-end use cases cannot be seen (they manually pass a large enough limit to stepDigest.
// The amount calculation in step is bypassed), so the decision itself is directly asserted here.
func TestDigestTickPlanDecouplesBatchSizeFromSendBudget(t *testing.T) {
	tokens, claimLimit := digestTickPlan()
	// One batch = one message = one request = one token. The unit of token is a message, not a vulnerability.
	if tokens != 1 {
		t.Fatalf("Summarizing a batch and sending only one message should consume exactly 1 token and get %d", tokens)
	}
	if claimLimit != db.MaxDigestBatchSize {
		t.Fatalf("The summary batch size should be the upper memory bound db.MaxDigestBatchSize=%d, get %d",
			db.MaxDigestBatchSize, claimLimit)
	}
	// Key relationship: The batch size must be much larger than the request budget per round. Once the two are of the same magnitude,
	// The explanation confused "send several messages" and "install several vulnerabilities in one batch" into one number.
	if claimLimit <= notifyMaxSendsPerChannelPerTick {
		t.Fatalf("汇总批次大小 %d 不应受每轮请求预算 %d 约束——"+
			"请求预算是由租约倒推的「发几次请求」，与「一批装几条漏洞」是两个量纲",
			claimLimit, notifyMaxSendsPerChannelPerTick)
	}
}

// TestNotifyTickBudgetFitsWithinLease is another anti-drift assertion.
//
// The upper limit of the number of delivery items per round for a single channel (notifyMaxSendsPerChannelPerTick) is deduced from the lease duration:
// The worst-case time for serial delivery in one round must be < lease, otherwise the leases for the next few leases will expire before they are sent out.
// When deploying multiple instances, the peer will retake them and send them repeatedly. These three constants are located in different locations,
// Changing either one will break the relationship without any error - so here's the nail in the coffin.
func TestNotifyTickBudgetFitsWithinLease(t *testing.T) {
	worst := time.Duration(notifyMaxSendsPerChannelPerTick) * notifySendTimeout
	if worst >= notifyLease {
		t.Fatalf("单渠道一轮的最坏耗时 %v 不应达到或超过租约 %v"+
			"（notifyMaxSendsPerChannelPerTick=%d × notifySendTimeout=%v）——"+
			"改这三个常量中的任意一个都要同步检查另外两个",
			worst, notifyLease, notifyMaxSendsPerChannelPerTick, notifySendTimeout)
	}
}
